    <script>
        document.addEventListener('DOMContentLoaded', function () {
            const emailInput = document.getElementById('email');
            const passwordInput = document.getElementById('password');
            const passwordToggle = document.getElementById('password-toggle');
            const statusPanel = document.getElementById('account-status-panel');
            const statusMessage = document.getElementById('account-status-message');
            const roleBadge = document.getElementById('account-role-badge');
            const lookupUrl = @js(route('login.lookup-role'));
            let lookupTimer = null;
            let activeRequest = null;

            const setStatus = (type, message, roleLabel = null) => {
                statusPanel.className = 'rounded-[22px] border px-4 py-3.5 transition-all duration-300';
                roleBadge.className = 'hidden rounded-full px-3 py-1 text-xs font-semibold';
                statusMessage.textContent = message;

                if (type === 'idle') {
                    statusPanel.classList.add('border-dashed', 'border-slate-200', 'bg-slate-50/90');
                    statusMessage.className = 'mt-1 text-sm font-medium text-slate-600';
                    return;
                }

                if (type === 'loading') {
                    statusPanel.classList.add('border-sky-200', 'bg-sky-50');
                    statusMessage.className = 'mt-1 text-sm font-medium text-sky-700';
                    return;
                }

                if (type === 'exists-admin') {
                    statusPanel.classList.add('border-sky-200', 'bg-sky-50');
                    statusMessage.className = 'mt-1 text-sm font-medium text-sky-800';
                    roleBadge.className = 'rounded-full bg-sky-100 px-3 py-1 text-xs font-semibold text-sky-700';
                    roleBadge.textContent = roleLabel ?? 'Admin';
                    return;
                }

                if (type === 'exists-student') {
                    statusPanel.classList.add('border-emerald-200', 'bg-emerald-50');
                    statusMessage.className = 'mt-1 text-sm font-medium text-emerald-800';
                    roleBadge.className = 'rounded-full bg-emerald-100 px-3 py-1 text-xs font-semibold text-emerald-700';
                    roleBadge.textContent = roleLabel ?? 'Pelajar';
                    return;
                }

                statusPanel.classList.add('border-rose-200', 'bg-rose-50');
                statusMessage.className = 'mt-1 text-sm font-medium text-rose-700';
            };

            passwordToggle?.addEventListener('click', function () {
                const reveal = passwordInput.type === 'password';
                passwordInput.type = reveal ? 'text' : 'password';
                passwordToggle.textContent = reveal ? 'Sembunyi' : 'Lihat';
                passwordToggle.setAttribute('aria-pressed', reveal ? 'true' : 'false');
                passwordToggle.setAttribute('aria-label', reveal ? 'Sembunyikan kata laluan' : 'Lihat kata laluan');
            });

            emailInput?.addEventListener('input', function () {
                const email = emailInput.value.trim();

                if (lookupTimer) {
                    clearTimeout(lookupTimer);
                }

                if (activeRequest) {
                    activeRequest.abort();
                    activeRequest = null;
                }

                if (!email) {
                    setStatus('idle', 'Masukkan e-mel untuk semakan akaun.');
                    return;
                }

                const looksLikeEmail = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);

                if (!looksLikeEmail) {
                    setStatus('idle', 'Lengkapkan format e-mel untuk semakan role.');
                    return;
                }

                lookupTimer = setTimeout(async function () {
                    setStatus('loading', 'Menyemak akaun...');
                    activeRequest = new AbortController();

                    try {
                        const response = await fetch(`${lookupUrl}?email=${encodeURIComponent(email)}`, {
                            headers: {
                                'Accept': 'application/json',
                                'X-Requested-With': 'XMLHttpRequest',
                            },
                            signal: activeRequest.signal,
                        });

                        if (!response.ok) {
                            throw new Error('Lookup failed');
                        }

                        const result = await response.json();

                        if (!result.exists) {
                            setStatus('missing', result.message ?? 'Akaun tidak wujud');
                            return;
                        }

                        if (result.role === 'admin') {
                            setStatus('exists-admin', `Peranan akaun: ${result.label}`, result.label);
                            return;
                        }

                        setStatus('exists-student', `Peranan akaun: ${result.label}`, result.label);
                    } catch (error) {
                        if (error.name === 'AbortError') {
                            return;
                        }

                        setStatus('missing', 'Semakan gagal. Cuba lagi sebentar.');
                    } finally {
                        activeRequest = null;
                    }
                }, 350);
            });

            if (emailInput?.value.trim()) {
                emailInput.dispatchEvent(new Event('input'));
            }
        });
    </script>
